import {Router} from 'express';
import {listVehicles,saveVehicle,availableBills,listPlans,getPlan,createPlan,changePlan,summaryPdf,modifyPlan} from '../controllers/delivery.controller.js';
const router=Router();
router.get('/vehicles',listVehicles);
router.post('/vehicles',saveVehicle);
router.put('/vehicles/:id',saveVehicle);
router.get('/available-bills',availableBills);
router.get('/plans',listPlans);
router.post('/plans',createPlan);
router.get('/plans/:id',getPlan);
router.patch('/plans/:id',changePlan);
router.post('/plans/:id/modify',modifyPlan);
router.get('/plans/:id/pdf/:kind',summaryPdf);
export default router;
